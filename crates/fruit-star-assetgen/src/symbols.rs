fn replay() -> Result<Art> {
    let (cx, cy, radius) = (512.0f32, 256.0f32, 172.0f32);
    let navy = "#0a2440";

    let mut defs = String::new();
    defs += &svg::linear(
        "replay-ring",
        0.0,
        40.0,
        0.0,
        472.0,
        &[(0.0, "#9af2ff"), (0.5, "#2aa8ee"), (1.0, "#1464c8")],
    );
    defs += &svg::linear(
        "replay-ribbon",
        0.0,
        166.0,
        0.0,
        346.0,
        &[(0.0, "#5cecd0"), (0.5, "#14b4a8"), (1.0, "#0a7c8c")],
    );
    let ribbon = "M64,166 L960,166 L918,256 L960,346 L64,346 L106,256 Z";
    let _ = write!(
        defs,
        "<clipPath id=\"replay-clip\"><path d=\"{ribbon}\"/></clipPath>"
    );

    // Two arrows chasing each other around a ring; the ribbon hides their tails.
    let point = |deg: f32, r: f32| -> (f32, f32) {
        let t = deg.to_radians();
        (cx + r * t.cos(), cy + r * t.sin())
    };
    let mut dark = String::new();
    let mut lit = String::new();
    for (start, end) in [(196.0f32, 290.0f32), (16.0, 110.0)] {
        let (sx, sy) = point(start, radius);
        let (ex, ey) = point(end, radius);
        let arc = format!("M{sx:.1},{sy:.1} A{radius},{radius} 0 0 1 {ex:.1},{ey:.1}");
        let _ = write!(
            dark,
            "<path d=\"{arc}\" fill=\"none\" stroke=\"{navy}\" stroke-width=\"70\"/>"
        );
        let _ = write!(
            lit,
            "<path d=\"{arc}\" fill=\"none\" stroke=\"url(#replay-ring)\" stroke-width=\"46\"/>"
        );
        // Arrow head: base across the ring at `end`, tip further along the circle.
        let t = (end - 0.5).to_radians();
        let (bx, by) = point(end - 0.5, radius);
        let (nx, ny) = (t.cos(), t.sin());
        let (tx, ty) = (-t.sin(), t.cos());
        let (half, len) = (60.0f32, 88.0f32);
        let sag = len * len / (2.0 * radius);
        let head = format!(
            "M{:.1},{:.1} L{:.1},{:.1} L{:.1},{:.1} Z",
            bx + nx * half,
            by + ny * half,
            bx + tx * len - nx * sag,
            by + ty * len - ny * sag,
            bx - nx * half,
            by - ny * half,
        );
        let _ = write!(
            dark,
            "<path d=\"{head}\" fill=\"{navy}\" stroke=\"{navy}\" stroke-width=\"24\" \
             stroke-linejoin=\"round\"/>"
        );
        let _ = write!(
            lit,
            "<path d=\"{head}\" fill=\"url(#replay-ring)\" stroke=\"url(#replay-ring)\" \
             stroke-width=\"2\" stroke-linejoin=\"round\"/>"
        );
    }

    let mut b = String::new();
    b += &dark;
    b += &lit;

    // Ribbon with notched ends.
    let _ = write!(
        b,
        "<path d=\"{ribbon}\" fill=\"url(#replay-ribbon)\" stroke=\"{navy}\" \
         stroke-width=\"{OUTLINE}\" stroke-linejoin=\"round\"/>"
    );
    let _ = write!(
        b,
        "<g clip-path=\"url(#replay-clip)\">\
         <rect x=\"40\" y=\"166\" width=\"944\" height=\"44\" fill=\"#ffffff\" opacity=\"0.22\"/>\
         <rect x=\"40\" y=\"312\" width=\"944\" height=\"40\" fill=\"#04465a\" opacity=\"0.28\"/>\
         <path d=\"{ribbon}\" fill=\"none\" stroke=\"#d8fff6\" stroke-width=\"20\" \
         stroke-linejoin=\"round\" opacity=\"0.55\"/></g>"
    );
    let _ = write!(
        b,
        "<path d=\"{ribbon}\" fill=\"none\" stroke=\"{navy}\" stroke-width=\"{OUTLINE}\" \
         stroke-linejoin=\"round\"/>"
    );

    let text = font::text_path_centered("REPLAY", 512.0, 256.0, 104.0, 0.26)?;
    b += &font::stroke(&text, navy, 42.0, "");
    b += &font::stroke(&text, "#ffffff", 22.0, "");

    Ok(Art { defs, body: b })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::raster;

    #[test]
    fn every_symbol_builds_and_parses() {
        for name in NAMES {
            let art = build(name).unwrap();
            let svg = document(name, &art);
            assert!(svg.contains("viewBox=\"0 0 1024 512\""));
            // Quarter-size render keeps the test quick while exercising the parser.
            let img = raster::render_svg(&svg, WIDTH / 4, HEIGHT / 4).unwrap();
            assert_eq!(
                img.pixel(0, 0)[3],
                0,
                "{name}: background must be transparent"
            );
            assert_eq!(img.pixel(WIDTH / 4 - 1, HEIGHT / 4 - 1)[3], 0, "{name}");
        }
    }

    #[test]
    fn symbols_are_centred_and_fill_the_cell() {
        for name in NAMES {
            let art = build(name).unwrap();
            let img = raster::render_svg(&document(name, &art), WIDTH / 2, HEIGHT / 2).unwrap();
            let (x0, y0, x1, y1) = img.alpha_bounds(8).unwrap();
            let (w, h) = ((x1 - x0 + 1) as f32 * 2.0, (y1 - y0 + 1) as f32 * 2.0);
            let (mx, my) = ((x0 + x1 + 1) as f32, (y0 + y1 + 1) as f32);
            assert!(
                x0 > 0 && y0 > 0 && x1 < WIDTH / 2 - 1 && y1 < HEIGHT / 2 - 1,
                "{name} clipped"
            );
            assert!((mx - 512.0).abs() <= 16.0, "{name}: off-centre in x ({mx})");
            assert!((my - 256.0).abs() <= 12.0, "{name}: off-centre in y ({my})");
            let wide = matches!(name, "bar" | "replay");
            if wide {
                assert!(
                    (0.8 * 1024.0..=0.93 * 1024.0).contains(&w),
                    "{name}: width {w}"
                );
                assert!(h >= 0.7 * 512.0, "{name}: height {h}");
            } else {
                assert!(
                    (0.82 * 512.0..=0.93 * 512.0).contains(&h),
                    "{name}: height {h}"
                );
            }
        }
    }

    #[test]
    fn unknown_symbol_is_an_error() {
        assert!(build("lemon").is_err());
    }
}
