/// Draws a bevelled five-point star made of ten facets lit from the upper left.
pub fn bevel_star(
    cx: f32,
    cy: f32,
    outer: f32,
    inner: f32,
    dark: &str,
    mid: &str,
    light: &str,
) -> String {
    let v = svg::star_vertices(cx, cy, outer, inner, 5);
    let mut out = String::new();
    for i in 0..v.len() {
        let (p, q) = (v[i], v[(i + 1) % v.len()]);
        // Outward normal of the facet's outer edge decides how much light it catches.
        let (ex, ey) = (q.0 - p.0, q.1 - p.1);
        let len = (ex * ex + ey * ey).sqrt().max(1e-6);
        let (nx, ny) = (ey / len, -ex / len);
        let lit = (nx * -0.55 + ny * -0.835) * 0.5 + 0.5;
        let color = if lit < 0.5 {
            svg::mix_hex(dark, mid, lit * 2.0)
        } else {
            svg::mix_hex(mid, light, (lit - 0.5) * 2.0)
        };
        let _ = write!(
            out,
            "<path d=\"M{cx:.2},{cy:.2} L{:.2},{:.2} L{:.2},{:.2} Z\" fill=\"{color}\" \
             stroke=\"{color}\" stroke-width=\"1.2\" stroke-linejoin=\"round\"/>",
            p.0, p.1, q.0, q.1
        );
    }
    out
}

fn star() -> Art {
    let (cx, cy, outer, inner) = (512.0f32, 278.0f32, 246.0f32, 125.0f32);
    let outline = svg::star_path(cx, cy, outer, inner);

    let mut defs = String::new();
    let _ = write!(
        defs,
        "<clipPath id=\"star-clip\"><path d=\"{outline}\"/></clipPath>"
    );

    let mut b = String::new();
    let _ = write!(
        b,
        "<path d=\"{outline}\" fill=\"#ffc21a\" stroke=\"{INK}\" stroke-width=\"14\" \
         stroke-linejoin=\"round\"/>"
    );
    b += &bevel_star(cx, cy, outer, inner, "#d67a00", "#ffbe18", "#ffec70");
    // Bright rim just inside the outline.
    let _ = write!(
        b,
        "<g clip-path=\"url(#star-clip)\"><path d=\"{outline}\" fill=\"none\" stroke=\"#fff8c0\" \
         stroke-width=\"28\" stroke-linejoin=\"round\" opacity=\"0.6\"/></g>"
    );
    let _ = write!(
        b,
        "<path d=\"{outline}\" fill=\"none\" stroke=\"{INK}\" stroke-width=\"{OUTLINE}\" \
         stroke-linejoin=\"round\"/>"
    );
    // Sparkle highlights.
    let _ = write!(
        b,
        "<path d=\"{}\" fill=\"#ffffff\"/>",
        svg::sparkle_path(446.0, 204.0, 42.0)
    );
    let _ = write!(
        b,
        "<path d=\"{}\" fill=\"#ffffff\" opacity=\"0.95\"/>",
        svg::sparkle_path(588.0, 330.0, 24.0)
    );
    let _ = write!(
        b,
        "<path d=\"{}\" fill=\"#ffffff\" opacity=\"0.9\"/>",
        svg::sparkle_path(512.0, 100.0, 17.0)
    );

    Art { defs, body: b }
}

