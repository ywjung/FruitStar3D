fn melon() -> Art {
    let (cx, cy, rx, ry) = (402.0f32, 272.0f32, 218.0f32, 200.0f32);
    let (ax, ay, ar) = (652.0f32, 180.0f32, 294.0f32);
    let (a0, a1) = (50.0f32.to_radians(), 118.0f32.to_radians());

    let mut defs = String::new();
    defs += &svg::radial_bbox(
        "melon-skin",
        0.36,
        0.28,
        0.85,
        &[(0.0, "#b6f066"), (0.45, "#45b438"), (1.0, "#166a25")],
    );
    defs += &svg::radial(
        "melon-flesh",
        ax,
        ay,
        ar - 40.0,
        &[(0.0, "#ff9a90"), (0.6, "#f5384c"), (1.0, "#d8162f")],
    );
    let _ = write!(
        defs,
        "<clipPath id=\"melon-clip\"><ellipse cx=\"{cx}\" cy=\"{cy}\" rx=\"{rx}\" ry=\"{ry}\"/>\
         </clipPath>"
    );

    let sector = |radius: f32| -> String {
        format!(
            "M{ax},{ay} L{:.1},{:.1} A{radius},{radius} 0 0 1 {:.1},{:.1} Z",
            ax + radius * a0.cos(),
            ay + radius * a0.sin(),
            ax + radius * a1.cos(),
            ay + radius * a1.sin(),
        )
    };

    let mut b = String::new();
    // Stalk.
    let stalk = format!(
        "M{cx},{} C{},{} {},{} {},{}",
        cy - ry + 8.0,
        cx - 2.0,
        56.0,
        cx + 12.0,
        44.0,
        cx + 30.0,
        42.0
    );
    b += &font::stroke(&stalk, INK, 28.0, "");
    b += &font::stroke(&stalk, "#8d5c24", 11.0, "");

    // Whole melon with wavy dark stripes following its curvature.
    let _ = write!(
        b,
        "<ellipse cx=\"{cx}\" cy=\"{cy}\" rx=\"{rx}\" ry=\"{ry}\" fill=\"url(#melon-skin)\"/>\
         <g clip-path=\"url(#melon-clip)\">"
    );
    for (i, k) in [-0.92f32, -0.56, -0.18, 0.2, 0.58, 0.94].iter().enumerate() {
        let bulge = k * rx;
        let mut d = String::new();
        let steps = 48;
        for s in 0..=steps {
            let t = s as f32 / steps as f32;
            let arc = (std::f32::consts::PI * t).sin();
            let wobble = 7.0 * (t * 40.0 + i as f32 * 1.7).sin() * arc;
            let x = cx + bulge * arc + wobble;
            let y = cy - ry * (std::f32::consts::PI * t).cos();
            let _ = write!(d, "{}{x:.1},{y:.1} ", if s == 0 { 'M' } else { 'L' });
        }
        let width = 30.0 - 10.0 * k.abs();
        b += &font::stroke(d.trim_end(), "#125c1f", width, "");
    }
    b += "</g>";
    b += &gloss(cx - 92.0, cy - 104.0, 46.0, 22.0, -36.0, 0.7);
    let _ = write!(
        b,
        "<ellipse cx=\"{cx}\" cy=\"{cy}\" rx=\"{rx}\" ry=\"{ry}\" fill=\"none\" stroke=\"{INK}\" \
         stroke-width=\"{OUTLINE}\"/>"
    );

    // Cut wedge in front: rind, pale inner rind, red flesh with seeds.
    b += &outlined(&sector(ar), "#1d7f2c", "");
    let _ = write!(b, "<path d=\"{}\" fill=\"#eaf8c4\"/>", sector(ar - 24.0));
    let _ = write!(
        b,
        "<path d=\"{}\" fill=\"url(#melon-flesh)\"/>",
        sector(ar - 42.0)
    );
    for (rho, deg) in [
        (118.0f32, 82.0f32),
        (158.0, 64.0),
        (166.0, 100.0),
        (204.0, 78.0),
        (212.0, 58.0),
        (214.0, 108.0),
        (222.0, 93.0),
    ] {
        let theta = deg.to_radians();
        let (sx, sy) = (ax + rho * theta.cos(), ay + rho * theta.sin());
        let _ = write!(
            b,
            "<ellipse cx=\"{sx:.1}\" cy=\"{sy:.1}\" rx=\"8.5\" ry=\"15\" \
             transform=\"rotate({:.1} {sx:.1} {sy:.1})\" fill=\"#2a0d0a\"/>",
            deg - 90.0
        );
    }
    // Wet highlight near the cut edge.
    let (hx0, hy0) = (
        ax + 70.0 * 108.0f32.to_radians().cos(),
        ay + 70.0 * 108.0f32.to_radians().sin(),
    );
    let (hx1, hy1) = (
        ax + 190.0 * 111.0f32.to_radians().cos(),
        ay + 190.0 * 111.0f32.to_radians().sin(),
    );
    b += &font::stroke(
        &format!("M{hx0:.1},{hy0:.1} L{hx1:.1},{hy1:.1}"),
        "#ffffff",
        11.0,
        "opacity=\"0.45\"",
    );
    let _ = write!(
        b,
        "<path d=\"{}\" fill=\"none\" stroke=\"{INK}\" stroke-width=\"{OUTLINE}\" \
         stroke-linejoin=\"round\"/>",
        sector(ar)
    );

    Art { defs, body: b }
}

