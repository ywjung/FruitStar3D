struct SevenStyle {
    id: &'static str,
    face: [&'static str; 3],
    edge: [&'static str; 3],
    star_cutout: bool,
}

impl SevenStyle {
    const RED: Self = Self {
        id: "red7",
        face: ["#ff6a55", "#ec1a26", "#99000f"],
        edge: ["#fff0a0", "#ffc21a", "#c77a00"],
        star_cutout: false,
    };
    const BLUE: Self = Self {
        id: "blue7",
        face: ["#8cf0ff", "#1e8ff2", "#0c38a8"],
        edge: ["#ffffff", "#cfd8e2", "#7d8a9a"],
        star_cutout: true,
    };
}

/// Silhouette shared by both sevens: a heavy top bar with a hanging serif and
/// a curved, tapering leg.
const SEVEN_PATH: &str = "M278,46 L734,46 L734,150 C644,236 588,344 574,458 L408,458 \
                          C420,340 480,248 584,166 L394,166 L388,218 L278,218 Z";

fn seven(style: &SevenStyle) -> Art {
    let id = style.id;
    let mut defs = String::new();
    defs += &svg::linear(
        &format!("{id}-face"),
        0.0,
        46.0,
        0.0,
        458.0,
        &[
            (0.0, style.face[0]),
            (0.45, style.face[1]),
            (1.0, style.face[2]),
        ],
    );
    defs += &svg::linear(
        &format!("{id}-edge"),
        0.0,
        60.0,
        0.0,
        480.0,
        &[
            (0.0, style.edge[0]),
            (0.5, style.edge[1]),
            (1.0, style.edge[2]),
        ],
    );
    let _ = write!(
        defs,
        "<clipPath id=\"{id}-clip\"><path d=\"{SEVEN_PATH}\"/></clipPath>"
    );

    let mut b = String::new();
    // Extruded drop edge towards the lower right.
    for (dx, dy, stroke) in [(18.0, 20.0, true), (12.0, 13.0, false), (6.0, 7.0, false)] {
        let stroke_attr = if stroke {
            format!("stroke=\"{INK}\" stroke-width=\"{OUTLINE}\" stroke-linejoin=\"round\"")
        } else {
            format!("stroke=\"url(#{id}-edge)\" stroke-width=\"2\"")
        };
        let _ = write!(
            b,
            "<path d=\"{SEVEN_PATH}\" transform=\"translate({dx} {dy})\" \
             fill=\"url(#{id}-edge)\" {stroke_attr}/>"
        );
    }
    // Face.
    let _ = write!(b, "<path d=\"{SEVEN_PATH}\" fill=\"url(#{id}-face)\"/>");
    let _ = write!(b, "<g clip-path=\"url(#{id}-clip)\">");
    // Glossy sheen across the upper left of the bar and a soft glint down the leg.
    b += "<path d=\"M250,30 L560,30 L440,240 L250,240 Z\" fill=\"#ffffff\" opacity=\"0.2\"/>";
    if style.star_cutout {
        // Design difference of the blue seven: pale stripes across the leg.
        for y in [300.0, 348.0, 396.0] {
            let _ = write!(
                b,
                "<path d=\"M380,{y} L640,{} \" fill=\"none\" stroke=\"#e8fbff\" \
                 stroke-width=\"16\" opacity=\"0.85\"/>",
                y - 30.0
            );
        }
    } else {
        b += "<path d=\"M640,170 C560,250 512,340 498,440\" fill=\"none\" stroke=\"#ffffff\" \
              stroke-width=\"16\" stroke-linecap=\"round\" opacity=\"0.22\"/>";
    }
    // White inner outline.
    let _ = write!(
        b,
        "<path d=\"{SEVEN_PATH}\" fill=\"none\" stroke=\"#ffffff\" stroke-width=\"34\" \
         stroke-linejoin=\"round\"/></g>"
    );
    // Dark outer outline.
    let _ = write!(
        b,
        "<path d=\"{SEVEN_PATH}\" fill=\"none\" stroke=\"{INK}\" stroke-width=\"{OUTLINE}\" \
         stroke-linejoin=\"round\"/>"
    );
    if style.star_cutout {
        // ... and a white star set into the top bar.
        let star = svg::star_path(506.0, 108.0, 44.0, 20.0);
        let _ = write!(
            b,
            "<path d=\"{star}\" fill=\"#ffffff\" stroke=\"#0c2f86\" stroke-width=\"7\" \
             stroke-linejoin=\"round\"/>"
        );
    }

    Art { defs, body: b }
}

