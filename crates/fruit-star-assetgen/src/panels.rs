/// Periodic value noise: `cells` lattice cells across the texture, wrapping on both axes.
fn tile_noise(rng: &mut Rng, size: u32, cells: u32) -> Vec<f32> {
    let lattice: Vec<f32> = (0..cells * cells).map(|_| rng.bipolar()).collect();
    let at = |cx: u32, cy: u32| lattice[((cy % cells) * cells + (cx % cells)) as usize];
    let smooth = |t: f32| t * t * (3.0 - 2.0 * t);
    let mut out = Vec::with_capacity((size * size) as usize);
    for y in 0..size {
        for x in 0..size {
            let fx = x as f32 * cells as f32 / size as f32;
            let fy = y as f32 * cells as f32 / size as f32;
            let (ix, iy) = (fx.floor() as u32, fy.floor() as u32);
            let (tx, ty) = (smooth(fx.fract()), smooth(fy.fract()));
            let top = at(ix, iy) + (at(ix + 1, iy) - at(ix, iy)) * tx;
            let bottom = at(ix, iy + 1) + (at(ix + 1, iy + 1) - at(ix, iy + 1)) * tx;
            out.push(top + (bottom - top) * ty);
        }
    }
    out
}

/// Cream reel-strip background that tiles seamlessly (vertically and horizontally).
pub fn reel_band_image() -> Image {
    let size = REEL_BAND_SIZE;
    let mut rng = Rng::new(0x5EED_0B0D);
    let coarse = tile_noise(&mut rng, size, 4);
    let medium = tile_noise(&mut rng, size, 16);
    let fine = tile_noise(&mut rng, size, 64);
    // Faint vertical "calendered plastic" streaks, constant along y.
    let streaks: Vec<f32> = (0..size).map(|_| rng.bipolar()).collect();

    let mut img = Image::solid(size, size, BAND_BASE);
    for y in 0..size {
        for x in 0..size {
            let i = (y * size + x) as usize;
            let grain = rng.bipolar();
            let mut delta = coarse[i] * 2.2 + medium[i] * 1.6 + fine[i] * 1.3 + grain * 1.1;
            delta += streaks[x as usize] * 0.7;
            // Edge guide lines and a hint of shading towards the band edges.
            let edge = x.min(size - 1 - x) as f32;
            delta -= 5.0 * (1.0 - (edge / 10.0).min(1.0)).powi(2);
            for line in BAND_LINE_X {
                let d = (x as f32 - line as f32 - 0.25).abs();
                delta -= 20.0 * (1.0 - d / 1.4).max(0.0);
            }
            let px = [
                (f32::from(BAND_BASE[0]) + delta).round().clamp(0.0, 255.0) as u8,
                (f32::from(BAND_BASE[1]) + delta).round().clamp(0.0, 255.0) as u8,
                (f32::from(BAND_BASE[2]) + delta * 1.15)
                    .round()
                    .clamp(0.0, 255.0) as u8,
                255,
            ];
            img.set_pixel(x, y, px);
        }
    }
    img
}

/// White stroke-font label on a transparent background; returns the SVG and its pixel width.
pub fn label_svg(text: &str) -> Result<(String, u32)> {
    let cap = 74.0f32;
    let stroke = 15.0f32;
    let pad = 14.0 + stroke / 2.0;
    let text_width = font::text_width(text, cap, 0.24)?;
    let width = (text_width + 2.0 * pad).ceil() as u32;
    let top = (LABEL_HEIGHT as f32 - cap) / 2.0;
    let path = font::text_path(text, (width as f32 - text_width) / 2.0, top, cap, 0.24)?;
    let mut doc = Doc::new(width, LABEL_HEIGHT);
    doc.push(&font::stroke(&path, "#ffffff", stroke, ""));
    Ok((doc.finish(&comment(&format!("label \"{text}\""))), width))
}

/// Pixel size of the pay table strip.
pub const PAYTABLE_SIZE: (u32, u32) = (2048, 256);

/// Pay table printed on the reel panel: every winning symbol with what three of them pay.
///
/// One column per role; the symbol sits above its payout. The texts mirror the default
/// machine profile (`config/machines/fruit_classic.toml`).
pub fn paytable_svg() -> Result<String> {
    const ENTRIES: [(&str, &str); 9] = [
        ("red_seven", "BIG"),
        ("blue_seven", "BIG"),
        ("bar", "REG"),
        ("star", "15"),
        ("melon", "12"),
        ("bell", "10"),
        ("grape", "8"),
        ("cherry", "4"),
        ("replay", "REPLAY"),
    ];
    let (width, height) = PAYTABLE_SIZE;
    let mut doc = Doc::new(width, height);
    let column = width as f32 / ENTRIES.len() as f32;
    let names: Vec<&str> = ENTRIES.iter().map(|(name, _)| *name).collect();
    let arts = add_symbols(&mut doc, &names)?;
    for (index, ((_, text), art)) in ENTRIES.iter().zip(&arts).enumerate() {
        let cx = column * (index as f32 + 0.5);
        // Symbol canvas is 1024x512; scaled so even the wide BAR / REPLAY fit the column.
        doc.place(art, &symbol_at(cx, 84.0, 0.205));
        let cap = if text.len() > 3 { 34.0 } else { 46.0 };
        let path = font::text_path_centered(text, cx, 206.0, cap, 0.2)?;
        doc.push(&font::stroke(&path, "#2a1206", cap * 0.42, ""));
        doc.push(&font::stroke(&path, "#ffe9a8", cap * 0.2, ""));
        if index > 0 {
            let x = column * index as f32;
            doc.push(&format!(
                "<line x1=\"{x}\" y1=\"26\" x2=\"{x}\" y2=\"230\" stroke=\"#ffffff\" \
                 stroke-opacity=\"0.22\" stroke-width=\"3\"/>"
            ));
        }
    }
    Ok(doc.finish(&comment("pay table strip")))
}

