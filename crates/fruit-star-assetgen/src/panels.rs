/// Transform that draws a 1024×512 symbol centred on (`cx`, `cy`) at `scale`.
fn symbol_at(cx: f32, cy: f32, scale: f32) -> String {
    format!("translate({cx} {cy}) scale({scale}) translate(-512 -256)")
}

fn add_symbols(doc: &mut Doc, names: &[&str]) -> Result<Vec<Art>> {
    names
        .iter()
        .map(|name| {
            let art = symbols::build(name)?;
            doc.defs(&art.defs);
            Ok(art)
        })
        .collect()
}

/// Alternating sunburst rays as one path.
fn rays(cx: f32, cy: f32, radius: f32, count: usize, phase: f32) -> String {
    let mut d = String::new();
    let step = std::f32::consts::TAU / count as f32;
    for i in (0..count).step_by(2) {
        let (a0, a1) = (phase + i as f32 * step, phase + (i + 1) as f32 * step);
        let _ = write!(
            d,
            "M{cx},{cy} L{:.1},{:.1} L{:.1},{:.1} Z ",
            cx + radius * a0.cos(),
            cy + radius * a0.sin(),
            cx + radius * a1.cos(),
            cy + radius * a1.sin(),
        );
    }
    d
}

/// A row of marquee bulbs around a rectangle inset by `inset`.
fn bulbs(width: f32, height: f32, inset: f32, spacing: f32, radius: f32, fill: &str) -> String {
    let mut out = String::new();
    let (w, h) = (width - 2.0 * inset, height - 2.0 * inset);
    let nx = (w / spacing).round().max(1.0) as usize;
    let ny = (h / spacing).round().max(1.0) as usize;
    let mut dot = |x: f32, y: f32| {
        let _ = write!(
            out,
            "<circle cx=\"{x:.1}\" cy=\"{y:.1}\" r=\"{radius}\" fill=\"{fill}\"/>"
        );
    };
    for i in 0..=nx {
        let x = inset + w * i as f32 / nx as f32;
        dot(x, inset);
        dot(x, height - inset);
    }
    for j in 1..ny {
        let y = inset + h * j as f32 / ny as f32;
        dot(inset, y);
        dot(width - inset, y);
    }
    out
}

