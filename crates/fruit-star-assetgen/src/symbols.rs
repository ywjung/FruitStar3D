//! The nine reel symbols, drawn as original vector illustrations.
//!
//! Each symbol lives on a 1024×512 canvas with a transparent background and
//! is centred on (512, 256). The style is a classic mechanical-slot print:
//! a thick dark outline, two- or three-tone gradients and glossy highlights.

use std::fmt::Write as _;

use anyhow::{Result, bail};

use crate::font;
use crate::svg::{self, Art, Doc};

/// Canvas size of every symbol.
pub const WIDTH: u32 = 1024;
pub const HEIGHT: u32 = 512;

/// File stems of all symbols, in paytable order.
pub const NAMES: [&str; 9] = [
    "grape",
    "cherry",
    "red_seven",
    "blue_seven",
    "bar",
    "bell",
    "melon",
    "star",
    "replay",
];

/// Shared outline colour (a warm near-black, as in printed reel strips).
const INK: &str = "#1d0f0a";
/// Outline thickness in canvas pixels.
const OUTLINE: f32 = 12.0;

/// Builds the artwork for the symbol called `name`.
pub fn build(name: &str) -> Result<Art> {
    Ok(match name {
        "grape" => grape(),
        "cherry" => cherry(),
        "red_seven" => seven(&SevenStyle::RED),
        "blue_seven" => seven(&SevenStyle::BLUE),
        "bar" => bar()?,
        "bell" => bell(),
        "melon" => melon(),
        "star" => star(),
        "replay" => replay()?,
        other => bail!("unknown symbol {other:?}"),
    })
}

/// Wraps a symbol's artwork into a standalone SVG document.
pub fn document(name: &str, art: &Art) -> String {
    let mut doc = Doc::new(WIDTH, HEIGHT);
    doc.add_art(art);
    doc.finish(&format!(
        "FRUIT STAR 3D reel symbol \"{name}\" - original procedural artwork generated by \
         fruit-star-assetgen (symbols.rs). No third-party material."
    ))
}

fn outlined(d: &str, fill: &str, extra: &str) -> String {
    format!(
        "<path d=\"{d}\" fill=\"{fill}\" stroke=\"{INK}\" stroke-width=\"{OUTLINE}\" \
         stroke-linejoin=\"round\" stroke-linecap=\"round\" {extra}/>"
    )
}

fn gloss(cx: f32, cy: f32, rx: f32, ry: f32, angle: f32, opacity: f32) -> String {
    format!(
        "<ellipse cx=\"{cx}\" cy=\"{cy}\" rx=\"{rx}\" ry=\"{ry}\" \
         transform=\"rotate({angle} {cx} {cy})\" fill=\"#ffffff\" opacity=\"{opacity}\"/>"
    )
}

